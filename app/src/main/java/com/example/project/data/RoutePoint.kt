package com.example.project.data


// =====================================================
// 一個 GPS 軌跡點
//
// 運動進行時先保存在 TrackingRepository。
// 之後結束運動時，再轉成後端需要的 GpsPointUpload。
// =====================================================

data class RoutePoint(


    // =================================================
    // 緯度
    // =================================================

    val latitude: Double,


    // =================================================
    // 經度
    // =================================================

    val longitude: Double,


    // =================================================
    // 海拔（公尺）
    //
    // GPS 不一定每次都有，所以允許 null。
    // =================================================

    val altitude: Double? = null,


    // =================================================
    // GPS 回報速度
    //
    // 單位：m/s
    // =================================================

    val speedMs: Double? = null,


    // =================================================
    // GPS 精準度
    //
    // 單位：公尺
    //
    // 例如：
    // accuracy = 5
    // 大約代表誤差半徑 5 公尺。
    // =================================================

    val accuracyMeters: Double? = null,


    // =================================================
    // 移動方向
    //
    // Android Location 的 bearing。
    // 0～360 度。
    // =================================================

    val heading: Double? = null,


    // =================================================
    // GPS 點產生時間
    //
    // 先保存成 Unix milliseconds。
    //
    // 例如：
    // 1790230800000
    //
    // 等真正上傳時，再轉成：
    //
    // 2026-09-24T08:00:00+08:00
    // =================================================

    val timestampMillis: Long =
        System.currentTimeMillis()
)